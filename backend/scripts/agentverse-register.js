// Phase 9 safe registration runbook. Agentverse generates the actual
// registration script in its UI; this script never sends credentials.

const { registrationPayload } = require('../src/agentverse/agentverse.readme')
const { identitySummary } = require('../src/agentverse/agentverse.identity')

function main() {
  const asJson = process.argv.includes('--json')
  const summary = identitySummary()
  const payload = registrationPayload()

  if (asJson) {
    console.log(JSON.stringify({ status: 'ready-to-register', registered: summary.registered, payload }, null, 2))
    return
  }

  console.log('================ CrisisFlow Agentverse Registration ================')
  console.log('Agent name      :', payload.name)
  console.log('Agent URI       :', summary.uri || '(not set; save the registered address here)')
  console.log('Adapter endpoint:', summary.externalEndpoint || '(not set)')
  console.log('Registered      :', summary.registered ? 'yes' : 'no (pending registration)')
  console.log('\nManual steps:')
  console.log('  1. Start Express, then run agentverse_adapter/main.py separately.')
  console.log('  2. Deploy the adapter at HTTPS; set AGENT_EXTERNAL_ENDPOINT.')
  console.log('     Public:  GET {AGENT_EXTERNAL_ENDPOINT}/status')
  console.log('              POST {AGENT_EXTERNAL_ENDPOINT}/chat')
  console.log('     Private: POST {CRISISFLOW_BACKEND_URL}/api/agent/chat')
  console.log('  3. In Agentverse: Launch an Agent -> Connect Agent -> FastAPI.')
  console.log('  4. Provide this name, the public adapter URL, and the keywords below.')
  console.log('  5. Run the registration script generated by Agentverse with your')
  console.log('     AGENTVERSE_API_KEY and AGENT_SEED_PHRASE, then save the address')
  console.log('     as AGENT_URI and select Evaluate Registration.')
  console.log('  6. Use Agentverse Testing before claiming ASI:One discovery.')
  console.log('\nCapabilities:')
  payload.capabilities.forEach((capability) => console.log('  -', capability))
  console.log('\nKeywords:')
  payload.keywords.forEach((keyword) => console.log('  -', keyword))
  console.log('\nREADME: backend/AGENTVERSE_README.md')
  console.log('=====================================================================')
}

main()
